def weighted_vote_predict(X, models_dict, weights):
    preds = {}
    for name, model in models_dict.items():
        if hasattr(model, 'predict_classes') or type(model).__name__ == 'Sequential':
            pred_proba = model.predict(X)
            preds[name] = (pred_proba > 0.5).astype(int).flatten()
        else:
            preds[name] = model.predict(X)
    final_preds = []
    num_samples = X.shape[0]
    model_names = list(models_dict.keys())
    for i in range(num_samples):
        vote_score = defaultdict(float)
        for idx, name in enumerate(model_names):
            pred = preds[name][i]
            vote_score[pred] += weights[idx]
        if not vote_score:
            final_decision = 0
        else:
            final_decision = max(vote_score.items(), key=lambda item: item[1])[0]
        final_preds.append(final_decision)
    return np.array(final_preds)

